class VectorValue(list):
    """A vector-valued expression during lowering.

    Tack scalarizes vectors: the value is one scalar IR expression per
    component, in storage order, and it never enters the IR itself. It is
    a ``list`` so code that maps over components stays plain. What the
    class adds is an identity distinct from a tuple of values and from a
    list of statements, and a ``shape``: ``(n,)`` for a vector.
    """

    def __init__(self, components, shape=None):
        super().__init__(components)
        self.shape = (len(self),) if shape is None else tuple(shape)

    def describe(self) -> str:
        if len(self.shape) == 1:
            return f"a {self.shape[0]}-vector"
        return "a " + "x".join(str(d) for d in self.shape) + " matrix"


class TupleValue(list):
    """Several values side by side: a tuple in the source.

    The indices of ``f[i, j]``, the right side of ``a, b = b, a``, and what
    a device function with ``return a, b`` yields. An item may itself be a
    ``VectorValue``.
    """

    def describe(self) -> str:
        return f"a tuple of {len(self)} values"


def _size(shape) -> int:
    total = 1
    for extent in shape:
        total *= extent
    return total


def _like(original, components):
    """``components`` as the kind of value ``original`` is."""
    if isinstance(original, VectorValue):
        return VectorValue(components, original.shape)
    if isinstance(original, TupleValue):
        return TupleValue(components)
    return list(components)


def _describe_value(value) -> str:
    describe = getattr(value, 'describe', None)
    return describe() if describe is not None else f"a list of {len(value)} values"


class KernelTransformer(ast.NodeVisitor):
    """Transforms a Python AST (from a @kernel function) into Tack IR.

    Tracks nesting depth to distinguish parallel for-loops (top-level)
    from sequential for-loops (nested inside another for-loop).

    Supports:
      - @tack.func inlining at call sites
      - Multi-dimensional field indexing: field[i, j] → field[i * shape1 + j]
      - field[None] → field[0] for scalar fields
      - ndrange(w, h) → 1D parallel loop with index decomposition
      - Vector scalarization: Vector([a, b, c]) → 3 scalar variables
    """

    def __init__(self, vector_fields=None, texture_fields=None, python_func=None,
                 bindings=None, template_funcs=None):
        self._python_func = python_func
        self._bindings = bindings
        self._template_funcs = template_funcs
        self._call_bindings = None
        # Lowered nodes already checked by _check_single_values, by id.
        self._checked_nodes = set()
        self._active_funcs = set()
        self._loop_depth = 0
        self._used_names: set[str] = set()
        self._component_names: dict[tuple[str, int], str] = {}
        self._inline_counter = 0  # unique suffix for inlined variables
        # Vector tracking: name → number of components
        self._vector_vars: dict[str, int] = {}
        # Statements generated by expression-level inlining (hoisted before current stmt)
        self._pre_stmts: list = []
        # Shared memory variables
        self._shared_vars: set[str] = set()
        # Vector field metadata: param_name → number of components. The
        # caller gives a matrix field as its (rows, columns); those are
        # kept beside the component count.
        self._vector_fields: dict[str, int] = {}
        self._matrix_fields: dict[str, tuple] = {}
        for name, width in (vector_fields or {}).items():
            if isinstance(width, tuple):
                self._matrix_fields[name] = width
                width = _size(width)
            self._vector_fields[name] = width
        # Matrix variables: name → (rows, columns), beside _vector_vars
        self._matrix_vars: dict[str, tuple] = {}
        # Texture field metadata: param_name → (W, H, D) shape
        self._texture_fields: dict[str, tuple] = texture_fields or {}
        # Maps renamed texture names back to the original kernel param name
        self._texture_origin: dict[str, str] = {}
        # Where each name is first read: name → (line, column, device
        # function it was inlined from or None). Only for diagnostics.
        self._name_reads: dict[str, tuple] = {}
        self._inline_stack: list[str] = []
        self._function_name = '<module>'
        # Statements outside the parallel loop may run any number of times
        # per launch (once per GPU thread, once per CPU chunk or probe), so
        # only effect-free ones are accepted there.
        self._kernel_body: list = []
        self._in_parallel_loop = False
        self._parallel_loop_seen = False

    def visit(self, node):
        try:
            return super().visit(node)
        except NotImplementedError as error:
            if isinstance(error, UnsupportedSyntaxError):
                raise
            line = getattr(node, 'lineno', 1)
            column = getattr(node, 'col_offset', 0) + 1
            raise UnsupportedSyntaxError(
                f"Kernel '{self._function_name}': {error} "
                f"at line {line}, column {column}") from error

    def visit_Module(self, node: ast.Module) -> ir.IRModule:
        module = ir.IRModule()
        for stmt in node.body:
            if isinstance(stmt, ast.FunctionDef):
                from tack.lang.call_bindings import CallBindings
                self._call_bindings = CallBindings(
                    stmt, self._python_func, self._bindings, self._template_funcs)
                validate_source(stmt, call_bindings=self._call_bindings)
                module.functions.append(self.visit_FunctionDef(stmt))
            else:
                raise NotImplementedError(f"Unsupported module statement: {type(stmt).__name__}")
        return module

    def generic_visit(self, node):
        raise NotImplementedError(f"Unsupported kernel syntax: {type(node).__name__}")

    def visit_Pass(self, node):
        return None

    def visit_FunctionDef(self, node: ast.FunctionDef) -> ir.IRFunction:
        self._function_name = node.name
        self._used_names.update(n.id for n in ast.walk(node) if isinstance(n, ast.Name))
        self._used_names.update(arg.arg for arg in node.args.args)
        params = []
        for arg in node.args.args:
            params.append(ir.IRParam(
                name=arg.arg,
                type_annotation=None,  # resolved during type inference
            ))
        self._kernel_body = node.body
        body = self._visit_body(node.body)
        if not self._parallel_loop_seen:
            raise self._source_error(
                node, "definition", "has no parallel loop: a kernel's work is "
                "the body of one top-level `for` loop over `range(...)` or "
                "`tack.ndrange(...)`")
        for stmt in body:
            if isinstance(stmt, ir.IRParallelFor):
                _mark_outermost_continues(stmt.body)
        function = ir.IRFunction(name=node.name, params=params, body=body)
        if workgroup_features(function):
            # Workgroup collectives assume one-dimensional groups.
            parallel_dims.flatten(parallel_dims.parallel_loop(function))
        self._check_names_bound(function)
        self._check_loop_variables_stay_in_their_loops(function)
        return function

    def _fresh_name(self, preferred):
        return fresh_name(preferred, self._used_names)

    def _source_error(self, node, construct, detail):
        """An UnsupportedSyntaxError at a kernel or inlined source position."""
        where = f"Kernel '{self._function_name}'"
        if self._inline_stack:
            where = (f"Device function '{self._inline_stack[-1]}' "
                     f"(inlined into kernel '{self._function_name}')")
        return UnsupportedSyntaxError(
            f"{where}: {construct} at line {node.lineno}, "
            f"column {node.col_offset + 1} {detail}")

    def _check_outside_parallel_loop(self, stmt, lowered: list):
        """Reject an observable effect lowered outside the parallel loop.

        Runs on each statement's lowered IR, so effects that arrive through
        inlined device functions, template methods, vector stores or tuple
        unpacking are all seen. Nested and inlined bodies are checked first,
        so the position is that of the innermost source statement.
        """
        for node in walk_ir([s for s in lowered if not isinstance(s, ir.IRParallelFor)]):
            effect = _effect_name(node)
            if effect is not None:
                raise self._source_error(
                    stmt, effect, "is outside the parallel loop. Statements "
                    "there may run any number of times per launch, so they "
                    "may only assign local variables and declare arrays; "
                    f"move the {effect} into the loop body")

    def _check_single_values(self, stmt, lowered: list):
        """Reject a vector or a tuple left where the IR needs one value.

        Vectors exist only during lowering, as lists of component
        expressions; every operation that accepts one maps over it. One
        that does not would otherwise put the list into the IR, where the
        verifier reports it as "expected expr node" with a tree path. Here
        the statement's source position is still known. Each lowered node
        is examined once: a nested body was checked when it was lowered.
        """
        pending = list(lowered)
        while pending:
            node = pending.pop()
            if id(node) in self._checked_nodes:
                continue
            self._checked_nodes.add(id(node))
            if isinstance(node, list):
                raise self._source_error(
                    stmt, "statement", f"uses {_describe_value(node)} where a single "
                    f"value is required")
            for name, role in child_fields(node):
                value = getattr(node, name)
                if role in LIST_ROLES:
                    pending.extend(value)
                elif value is not None:
                    pending.append(value)

    def _component_name(self, name, component):
        key = (name, component)
        if key not in self._component_names:
            self._component_names[key] = self._fresh_name(f"{name}__{component}")
        return self._component_names[key]

    def _check_names_bound(self, function: ir.IRFunction):
        """Reject a read of a name the kernel never binds.

        The usual cause is a module-level Python value: a kernel is compiled
        from its own source and captures nothing from the enclosing scope.
        The IR verifier would refuse the same thing a moment later, but only
        as a tree path into the lowered IR; here the source position is still
        known. Existence only -- not definite assignment on every path.
        """
        bound = {p.name for p in function.params}
        used = []
        for n in walk_ir(function.body):
            if isinstance(n, ir.IRAssign):
                bound.add(n.target)
            elif isinstance(n, (ir.IRParallelFor, ir.IRSequentialFor)):
                bound.add(n.var)
                bound.update(getattr(n, 'dims', None) or ())
            elif isinstance(n, (ir.IRSharedAlloc, ir.IRLocalAlloc)):
                bound.add(n.name)
            elif isinstance(n, ir.IRName):
                used.append(n.name)
            elif isinstance(n, (ir.IRDimSize, ir.IRTextureSample)):
                used.append(n.field_name)
        for name in used:
            if name in bound:
                continue
            where = f"Kernel '{function.name}'"
            read = self._name_reads.get(name)
            at = ""
            if read is not None:
                line, column, inlined_from = read
                at = f" at line {line}, column {column}"
                if inlined_from is not None:
                    where = (f"Device function '{inlined_from}' "
                             f"(inlined into kernel '{function.name}')")
            raise NameError(
                f"{where}: name '{name}'{at} is not a parameter and is never "
                f"assigned. Kernels do not capture Python variables from the "
                f"enclosing scope: define it as {name} = tack.constant(...), "
                f"pass the value as an argument, or make it a class-level "
                f"constant of a @tack.data_oriented template.")

    def _check_loop_variables_stay_in_their_loops(self, function: ir.IRFunction):
        """Reject a read of a loop variable after its loop.

        A `for` loop's variable is a binding of its own that ends with the
        loop, on every backend: afterwards the name means whatever it meant
        before the loop, or nothing. Python would give the last value
        iterated. Rather than compute either silently -- CPU raised a
        NameError at codegen while the GPU backends failed to compile --
        refuse the read here, with its source position. A name whose most
        recent binding in program order is a loop header may not be read
        until it is assigned again. Branches and loops that may not run are
        merged conservatively: the name stays stale if it is stale on any
        path, so `assign it before the loop` is always a valid fix.
        """
        def read(expr, stale):
            for n in walk_ir(expr):
                if isinstance(n, ir.IRName) and n.name in stale:
                    raise self._loop_variable_error(function, n)

        def block(stmts, stale):
            stale = set(stale)
            for s in stmts:
                if isinstance(s, ir.IRAssign):
                    read(s.value, stale)
                    stale.discard(s.target)
                elif isinstance(s, (ir.IRSequentialFor, ir.IRParallelFor)):
                    for bound in (s.start, s.end, getattr(s, "step", None)):
                        if bound is not None:
                            read(bound, stale)
                    inner = block(s.body, stale - {s.var})
                    stale = (stale | inner) | {s.var}
                elif isinstance(s, ir.IRWhile):
                    read(s.condition, stale)
                    stale = stale | block(s.body, stale)
                elif isinstance(s, ir.IRIf):
                    read(s.condition, stale)
                    stale = block(s.then_body, stale) | block(s.else_body or [], stale)
                else:
                    read(s, stale)
            return stale

        block(function.body, set())

    def _loop_variable_error(self, function, name_node):
        where = f"Kernel '{function.name}'"
        at = ""
        read = getattr(name_node, "_source", None) or self._name_reads.get(name_node.name)
        if read is not None:
            line, column, inlined_from = read
            at = f" at line {line}, column {column}"
            if inlined_from is not None:
                where = (f"Device function '{inlined_from}' "
                         f"(inlined into kernel '{function.name}')")
        spelled = getattr(name_node, "_source_id", name_node.name)
        return NameError(
            f"{where}: name '{spelled}'{at} is read after the `for` loop "
            f"that bound it. A loop variable's binding ends with its loop; "
            f"to use the value afterwards, copy it to another name inside the "
            f"loop, or assign the name again before reading it.")

    def _visit_body(self, stmts: list) -> list:
        """Visit a list of statements, filtering out None results.

        Also collects any pre-statements generated by expression-level
        inlining of @tack.func calls and inserts them before the statement
        that triggered them.
        """
        saved_pre_stmts = self._pre_stmts
        result = []
        for stmt in stmts:
            self._pre_stmts = []
            visited = self.visit(stmt)
            # Insert any hoisted inline statements before this statement
            lowered = self._pre_stmts
            self._pre_stmts = []
            if visited is not None:
                if isinstance(visited, list):
                    lowered.extend(visited)
                else:
                    lowered.append(visited)
            if not self._in_parallel_loop:
                self._check_outside_parallel_loop(stmt, lowered)
            self._check_single_values(stmt, lowered)
            result.extend(lowered)
        self._pre_stmts = saved_pre_stmts
        return result

    def _visit_expression(self, node):
        """Capture the statements needed to evaluate exactly this expression."""
        saved = self._pre_stmts
        self._pre_stmts = []
        value = self.visit(node)
        statements = self._pre_stmts
        self._pre_stmts = saved
        return value, statements

    def _capture_value(self, value, statements, *, freeze_name=False):
        """Evaluate a delayed value before a later operand's side effects."""
        if isinstance(value, list):
            return _like(value, [self._capture_value(v, statements) for v in value])
        if isinstance(value, ir.IRConstant) or (isinstance(value, ir.IRName) and not freeze_name):
            return value
        name = self._fresh_name(f"__eval_{self._inline_counter}__")
        self._inline_counter += 1
        statements.append(ir.IRAssign(name, value))
        return ir.IRName(name)

    def _visit_ordered(self, nodes):
        """Preserve left-to-right evaluation across expression-level inlining."""
        values = []
        for node in nodes:
            value, statements = self._visit_expression(node)
            if statements:
                values = [self._capture_value(v, self._pre_stmts) for v in values]
                self._pre_stmts.extend(statements)
            values.append(value)
        return values

    # --- Loops ---

    def visit_For(self, node: ast.For) -> ir.IRNode:
        if not self._in_parallel_loop:
            return self._visit_parallel_for(node)
        return self._visit_for(node)

    def _visit_parallel_for(self, node: ast.For) -> ir.IRParallelFor:
        """Lower the kernel's one parallel loop, a statement of its own body."""
        if self._parallel_loop_seen or not any(node is s for s in self._kernel_body):
            raise self._source_error(
                node, "for loop", "is outside the parallel loop. A kernel has "
                "one parallel loop, a `for` statement directly in its body; "
                "sequential loops belong inside it")
        self._parallel_loop_seen = True
        return self._visit_for(node)

    def _visit_for_body(self, stmts: list) -> list:
        """Lower a for-loop body, which always lies inside the parallel loop.

        Its range arguments were lowered before, where the loop is entered.
        """
        saved = self._in_parallel_loop
        self._in_parallel_loop = True
        self._loop_depth += 1
        body = self._visit_body(stmts)
        self._loop_depth -= 1
        self._in_parallel_loop = saved
        return body

    def _visit_for(self, node: ast.For) -> ir.IRNode:
        target = node.target

        if node.orelse:
            raise NotImplementedError("'else' clause on for-loop not supported in kernels")

        # Handle tuple targets: for i, j in ndrange(w, h)
        if isinstance(target, ast.Tuple):
            return self._visit_ndrange_for(node)

        if not isinstance(target, ast.Name):
            raise NotImplementedError("Only simple loop variables supported")

        # Detect for i in range(...)
        if not self._is_range_call(node.iter):
            raise NotImplementedError("Only range() loops supported in kernels")

        start, end, step = self._parse_range_args(node.iter)
        if self._loop_depth:
            # Python's range evaluates its arguments once, before entering
            # the loop, even when the body rebinds a bound or step variable.
            start = self._capture_value(start, self._pre_stmts, freeze_name=True)
            end = self._capture_value(end, self._pre_stmts, freeze_name=True)
            if step is not None:
                step = self._capture_value(step, self._pre_stmts, freeze_name=True)

        body = self._visit_for_body(node.body)

        # Top-level for-range is parallel; nested for-range is sequential
        if self._loop_depth == 0:
            if step is not None:
                # Transform: for i in range(start, end, step)
                # Into: for __step_idx__ in range(0, (end - start + step - 1) // step):
                #            i = start + __step_idx__ * step
                idx_name = self._fresh_name(f"__step_idx_{self._inline_counter}__")
                self._inline_counter += 1
                total = ir.IRBinOp(
                    op="//",
                    left=ir.IRBinOp(op="+",
                        left=ir.IRBinOp(op="-", left=end, right=start),
                        right=ir.IRBinOp(op="-", left=step, right=ir.IRConstant(1))),
                    right=step,
                )
                decomp = ir.IRAssign(
                    target=target.id,
                    value=ir.IRBinOp(op="+", left=start,
                        right=ir.IRBinOp(op="*", left=ir.IRName(idx_name), right=step)),
                )
                return ir.IRParallelFor(var=idx_name, start=ir.IRConstant(0),
                                        end=total, body=[decomp, *body])
            if not (isinstance(start, ir.IRConstant) and start.value == 0):
                # Every backend launches the grid over [0, n) and never sees
                # the start, so it has to live in the body.
                # Transform: for i in range(start, end)
                # Into: for __start_idx__ in range(0, end - start):
                #            i = start + __start_idx__
                idx_name = self._fresh_name(f"__start_idx_{self._inline_counter}__")
                self._inline_counter += 1
                decomp = ir.IRAssign(
                    target=target.id,
                    value=ir.IRBinOp(op="+", left=start, right=ir.IRName(idx_name)),
                )
                return ir.IRParallelFor(
                    var=idx_name, start=ir.IRConstant(0),
                    end=ir.IRBinOp(op="-", left=end, right=start),
                    body=[decomp, *body])
            return ir.IRParallelFor(var=target.id, start=start, end=end, body=body)
        return ir.IRSequentialFor(var=target.id, start=start, end=end,
                                  body=body, step=step)

    def _visit_ndrange_for(self, node: ast.For):
        """Handle: for i, j in ndrange(w, h) or for i, j in tack.ndrange(w, h).

        Each argument is a size, counting from zero, or a ``(start, end)``
        pair: ``ndrange((1, n - 1), (1, m - 1))`` visits the interior. An
        empty or reversed pair makes the whole loop empty.
        """
        target = node.target
        if not isinstance(target, ast.Tuple):
            raise NotImplementedError("ndrange requires tuple target")

        names = []
        for elt in target.elts:
            if not isinstance(elt, ast.Name):
                raise NotImplementedError("ndrange targets must be simple names")
            names.append(elt.id)

        # Parse ndrange call
        call = node.iter
        if not isinstance(call, ast.Call):
            raise NotImplementedError("Expected ndrange() call")

        func_name = self._resolve_call_name(call)
        if func_name != "ndrange":
            raise NotImplementedError(f"Expected ndrange(), got {func_name}()")

        if len(call.args) != len(names):
            raise NotImplementedError(
                f"ndrange() dimension count ({len(call.args)}) must match "
                f"target count ({len(names)})"
            )

        starts = []
        dim_exprs = []
        for arg in call.args:
            if isinstance(arg, ast.Tuple):
                if len(arg.elts) != 2:
                    raise NotImplementedError(
                        "an ndrange() range is a (start, end) pair")
                start, end = self._visit_ordered(arg.elts)
                starts.append(start)
                # Clamp at zero: a reversed pair must not turn into a count
                # that another reversed pair makes positive again.
                dim_exprs.append(ir.IRCall(func_name="max", args=[
                    ir.IRBinOp(op="-", left=end, right=start), ir.IRConstant(0)]))
            else:
                starts.append(None)
                dim_exprs.append(self.visit(arg))

        # Compute total = dim0 * dim1 * ...
        total = dim_exprs[0]
        for d in dim_exprs[1:]:
            total = ir.IRBinOp(op="*", left=total, right=d)

        if self._loop_depth == 0 and len(names) in (2, 3):
            # The backend binds one index per dimension from a launch of
            # the same shape (see parallel_dims); nothing divides.
            idx_name = self._fresh_name(f"__nd_idx_{self._inline_counter}__")
            dims = [self._fresh_name(f"__nd_{self._inline_counter}_{k}__")
                    for k in range(len(names))]
            self._inline_counter += 1
            offsets = [ir.IRAssign(target=name, value=self._offset_index(start, ir.IRName(dim)))
                       for name, start, dim in zip(names, starts, dims)]
            body_stmts = self._visit_for_body(node.body)
            return ir.IRParallelFor(var=idx_name, start=ir.IRConstant(0), end=total,
                                    body=offsets + body_stmts, dims=dims,
                                    extents=list(dim_exprs))

        # Build body: decompose linear index into multi-dim indices
        # for __nd_idx__ in range(total):
        #     i = __nd_idx__ // dim1
        #     j = __nd_idx__ % dim1
        # For 3D: i = idx // (d1*d2), j = (idx // d2) % d1, k = idx % d2
        idx_name = self._fresh_name(f"__nd_idx_{self._inline_counter}__")
        self._inline_counter += 1

        decomp_stmts = []
        remaining = ir.IRName(idx_name)

        for k in range(len(names) - 1):
            # Product of remaining dimensions
            tail_product = dim_exprs[k + 1]
            for d in dim_exprs[k + 2:]:
                tail_product = ir.IRBinOp(op="*", left=tail_product, right=d)

            decomp_stmts.append(ir.IRAssign(target=names[k], value=self._offset_index(
                starts[k], ir.IRBinOp(op="//", left=remaining, right=tail_product))))
            remaining = ir.IRBinOp(op="%", left=remaining, right=tail_product)

        # Last dimension gets the remainder
        decomp_stmts.append(ir.IRAssign(
            target=names[-1], value=self._offset_index(starts[-1], remaining)))

        body_stmts = self._visit_for_body(node.body)

        full_body = decomp_stmts + body_stmts

        if self._loop_depth == 0:
            return ir.IRParallelFor(
                var=idx_name, start=ir.IRConstant(0), end=total, body=full_body)
        return ir.IRSequentialFor(
            var=idx_name, start=ir.IRConstant(0), end=total, body=full_body)

    @staticmethod
    def _offset_index(start, index):
        """An ndrange index counted from its range's start, if it has one."""
        return index if start is None else ir.IRBinOp(op="+", left=start, right=index)

    def visit_While(self, node: ast.While) -> ir.IRWhile:
        if node.orelse:
            raise NotImplementedError("'else' clause on while-loop not supported in kernels")
        condition, condition_stmts = self._visit_expression(node.test)
        condition = self._scalar_condition(node, "while", condition)
        self._loop_depth += 1
        body = self._visit_body(node.body)
        self._loop_depth -= 1
        if condition_stmts:
            # The condition's inlined calls execute on every test, including
            # after continue, rather than once before entering the loop.
            body = [*condition_stmts,
                    ir.IRIf(ir.IRUnaryOp('not', condition), [ir.IRBreak()], []),
                    *body]
            condition = ir.IRConstant(1)
        return ir.IRWhile(condition=condition, body=body)

    def visit_Break(self, node: ast.Break) -> ir.IRBreak:
        return ir.IRBreak()

    def visit_Continue(self, node: ast.Continue) -> ir.IRContinue:
        return ir.IRContinue()

    # --- Control flow ---

    def _scalar_condition(self, node, construct: str, condition):
        if isinstance(condition, list):
            raise self._source_error(
                node, construct, f"has {_describe_value(condition)} as its condition; "
                f"reduce it with any(...) or all(...), or select per component with "
                f"tack.select(mask, a, b)")
        return condition

    def visit_If(self, node: ast.If) -> ir.IRIf:
        condition = self._scalar_condition(node, "if", self.visit(node.test))
        then_body = self._visit_body(node.body)
        else_body = self._visit_body(node.orelse)
        return ir.IRIf(condition=condition, then_body=then_body, else_body=else_body)

    def visit_IfExp(self, node: ast.IfExp) -> ir.IRIfExp:
        condition, before = self._visit_expression(node.test)
        then_value, then_stmts = self._visit_expression(node.body)
        else_value, else_stmts = self._visit_expression(node.orelse)
        self._pre_stmts.extend(before)
        if isinstance(then_value, list) or isinstance(else_value, list):
            return self._vector_conditional(
                node, condition, then_value, then_stmts, else_value, else_stmts)
        if then_stmts or else_stmts:
            name = self._fresh_name(f"__conditional_{self._inline_counter}__")
            self._inline_counter += 1
            self._pre_stmts.append(ir.IRIf(
                condition,
                [*then_stmts, ir.IRAssign(name, then_value)],
                [*else_stmts, ir.IRAssign(name, else_value)],
            ))
            return ir.IRName(name)
        return ir.IRIfExp(condition, then_value, else_value)

    def _vector_conditional(self, node, condition, then_value, then_stmts,
                            else_value, else_stmts):
        """``a if c else b`` with a vector arm: one selection per component.

        The condition is evaluated once. An arm that needs statements of
        its own (an inlined call) runs them only when it is selected.
        """
        shape = self._common_shape(node, "conditional expression", [then_value, else_value])
        then_value, else_value = zip(*self._componentwise(
            node, "conditional expression", [then_value, else_value]), strict=True)
        if then_stmts or else_stmts:
            names = []
            for _ in then_value:
                names.append(self._fresh_name(f"__conditional_{self._inline_counter}__"))
                self._inline_counter += 1
            self._pre_stmts.append(ir.IRIf(
                condition,
                [*then_stmts, *(ir.IRAssign(n, v) for n, v in zip(names, then_value))],
                [*else_stmts, *(ir.IRAssign(n, v) for n, v in zip(names, else_value))],
            ))
            return VectorValue([ir.IRName(n) for n in names], shape)
        condition = self._capture_value(condition, self._pre_stmts)
        return VectorValue(
            [ir.IRIfExp(condition, t, e) for t, e in zip(then_value, else_value)], shape)

    # --- Assignments ---

    def visit_Assign(self, node: ast.Assign) -> ir.IRNode:
        if len(node.targets) != 1:
            raise NotImplementedError("Multiple assignment targets not supported")

        target = self._component_target(node.targets[0])
        value = node.value

        # Tuple unpacking: a, b = expr
        if isinstance(target, ast.Tuple):
            return self._visit_tuple_unpack(target, value)

        # Check for shared memory allocation: smem = tack.shared(tack.f32, 256)
        #                             or: smem = tack.shared_like(field, 256)
        if isinstance(target, ast.Name) and isinstance(value, ast.Call):
            shared_result = self._try_parse_shared_alloc(target.id, value)
            if shared_result is not None:
                return shared_result
            shared_like_result = self._try_parse_shared_like(target.id, value)
            if shared_like_result is not None:
                return shared_like_result

        # Check for local array allocation: arr = tack.local_array(tack.f32, 8)
        #                            or: arr = tack.local_array_like(field, 8)
        if isinstance(target, ast.Name) and isinstance(value, ast.Call):
            local_result = self._try_parse_local_alloc(target.id, value)
            if local_result is not None:
                return local_result
            local_like_result = self._try_parse_local_array_like(target.id, value)
            if local_like_result is not None:
                return local_like_result

        if (isinstance(target, ast.Name) and isinstance(value, ast.Name)
                and value.id in self._shared_vars):
            # An array is storage, not a value: C has no array assignment,
            # and binding a second name to it lowers to a scalar copy.
            raise NotImplementedError(
                f"cannot bind '{target.id}' to the local or shared array "
                f"'{value.id}'; index '{value.id}' directly, or pass it to "
                f"a @tack.func")

        # Check for vector construction: v = tack.Vector([a, b, c])
        vec_elts = self._try_parse_vector_construct(value)
        if vec_elts is not None and isinstance(target, ast.Name):
            return self._assign_vector(target.id, vec_elts)

        visited_value = self.visit(value)

        # v[c] = expr for a vector variable: assign the component
        if (isinstance(target, ast.Subscript) and isinstance(target.value, ast.Name)
                and target.value.id in self._vector_vars):
            return self._store_vector_component(target, visited_value)

        # vf[i][c] = expr for a vector field: store the component
        if self._is_field_component(target):
            return self._assign_field_component(target, visited_value)

        # Check if RHS is a vector variable → propagate vector-ness
        if isinstance(visited_value, list):
            if any(isinstance(component, list) for component in visited_value):
                raise self._source_error(
                    node, "assignment", "binds one target to several values, some of "
                    "them vectors; unpack them into one target each")
            # Vector expression result (list of IR nodes)
            if isinstance(target, ast.Name):
                return self._assign_vector_from_ir(target.id, visited_value)
            # Vector store: field[i] = vec_var
            if isinstance(target, ast.Subscript):
                return self._store_vector_field(target, visited_value)

        # field[i] = expr  →  IRFieldStore
        if isinstance(target, ast.Subscript):
            if isinstance(target.value, ast.Name) and target.value.id in self._vector_fields:
                # A scalar sets every component of the element, as it does
                # in vf[i] *= 2.0; the subscript names an element here just
                # as it does in a load.
                value = self._capture_value(visited_value, self._pre_stmts)
                shape = self._field_shape(target.value.id)
                return self._store_vector_field(
                    target, VectorValue([value] * _size(shape), shape))
            field, index, visited_value = self._visit_store_location(target, visited_value)
            return ir.IRFieldStore(field=field, index=index, value=visited_value)

        # x = expr  →  IRAssign
        if isinstance(target, ast.Name):
            # Clear vector tracking if reassigning to scalar
            self._vector_vars.pop(target.id, None)
            return ir.IRAssign(target=target.id, value=visited_value)

        raise NotImplementedError(f"Unsupported assignment target: {type(target).__name__}")

    def visit_AugAssign(self, node: ast.AugAssign) -> ir.IRNode:
        target = self._component_target(node.target)
        op = self._binop_str(node.op)

        # Check for vector augmented assignment: v += w
        if isinstance(target, ast.Name) and target.id in self._vector_vars:
            ndim = self._vector_vars[target.id]
            rhs_components = self._visit_as_vector(node.value, ndim)
            names = [self._component_name(target.id, c) for c in range(ndim)]
            stmts = []
            updated = self._settle_components(
                [ir.IRBinOp(op=op, left=ir.IRName(name), right=rhs)
                 for name, rhs in zip(names, rhs_components)], stmts, names)
            for name, value in zip(names, updated):
                stmts.append(ir.IRAssign(target=name, value=value))
            return stmts

        # v[c] += expr for a vector variable: read the component, store it back
        if (isinstance(target, ast.Subscript) and isinstance(target.value, ast.Name)
                and target.value.id in self._vector_vars):
            read = self.visit(target)
            right, statements = self._visit_expression(node.value)
            self._pre_stmts.extend(statements)
            return self._store_vector_component(
                target, ir.IRBinOp(op=op, left=read, right=right))

        # vf[i][c] += expr, and vf[i] += vec, for a vector field
        if self._is_field_component(target):
            return self._augment_field_component(target, op, node.value)
        if (isinstance(target, ast.Subscript) and isinstance(target.value, ast.Name)
                and target.value.id in self._vector_fields):
            return self._augment_vector_field(target, op, node.value)

        left = self.visit(target)
        # Evaluate a subscript once, reusing its address for the store.
        if isinstance(left, ir.IRFieldLoad):
            left.index = self._capture_value(left.index, self._pre_stmts)
        right, statements = self._visit_expression(node.value)
        if statements:
            read = self._capture_value(left, self._pre_stmts)
            self._pre_stmts.extend(statements)
        else:
            read = left
        if isinstance(right, list):
            raise self._source_error(
                node, "augmented assignment", "combines a scalar target with a vector")
        rhs = ir.IRBinOp(op=op, left=read, right=right)

        if isinstance(target, ast.Subscript):
            return ir.IRFieldStore(field=left.field, index=left.index, value=rhs)

        if isinstance(target, ast.Name):
            return ir.IRAssign(target=target.id, value=rhs)

        raise NotImplementedError("Unsupported augmented assignment target")

    def visit_Return(self, node: ast.Return) -> ir.IRReturn:
        value = self.visit(node.value) if node.value else None
        return ir.IRReturn(value=value)

    def _visit_tuple_unpack(self, target: ast.Tuple, value_node: ast.expr) -> list:
        """Handle tuple unpacking: a, b = expr.

        The whole right side is evaluated first, and then the targets are
        assigned from left to right, as Python does: in ``a[i], i = x, j``
        the store uses the old ``i``, and in ``i, a[i] = j, x`` the new one.
        A target that is not a plain name (``x[i]``, ``v.x``) receives its
        value through a temporary and is stored at its own position in
        that order.
        """
        names = []
        stores = {}     # temporary → the subscript or component target it is for
        for elt in target.elts:
            if isinstance(elt, ast.Name):
                names.append(elt.id)
            elif isinstance(elt, (ast.Subscript, ast.Attribute)):
                temp = self._fresh_name(f"__unpack_target_{self._inline_counter}__")
                self._inline_counter += 1
                names.append(temp)
                stores[temp] = elt
            else:
                raise NotImplementedError(
                    "Only names, subscripts and vector components in tuple unpacking")
        n = len(names)

        # Tuple literal RHS: a, b = b, a (need temps for correct swap)
        if isinstance(value_node, ast.Tuple):
            if len(value_node.elts) != n:
                raise TypeError(
                    f"Tuple unpacking: expected {n} values, got {len(value_node.elts)}")
            stmts = []
            temps = []
            for i, val in enumerate(self._visit_ordered(value_node.elts)):
                tmp = self._fresh_name(f"__unpack_tmp_{self._inline_counter}_{i}__")
                if isinstance(val, list):
                    ndim = len(val)
                    self._bind_vector(tmp, val)
                    for c, comp in enumerate(val):
                        stmts.append(ir.IRAssign(target=self._component_name(tmp, c), value=comp))
                    temps.append(('vector', tmp, ndim))
                else:
                    stmts.append(ir.IRAssign(target=tmp, value=val))
                    temps.append(('scalar', tmp, None))
            self._inline_counter += 1
            # Assign temps to targets
            for name, (kind, tmp, ndim) in zip(names, temps):
                if kind == 'vector':
                    self._bind_vector(name, self._variable_value(tmp))
                    for c in range(ndim):
                        stmts.append(ir.IRAssign(
                            target=self._component_name(name, c),
                            value=ir.IRName(self._component_name(tmp, c))))
                else:
                    self._vector_vars.pop(name, None)
                    stmts.append(ir.IRAssign(target=name, value=ir.IRName(tmp)))
                stmts.extend(self._store_unpacked(name, stores))
            return stmts

        # Expression RHS (e.g., multi-return from @tack.func)
        visited_value = self.visit(value_node)

        if isinstance(visited_value, list):
            if len(visited_value) != n:
                raise TypeError(
                    f"Tuple unpacking: expected {n} values, got {len(visited_value)}")
            stmts = []
            if stores:
                # A store among the targets can change what a later value
                # reads, so every value is evaluated before the first one.
                visited_value = _like(visited_value, [
                    _like(val, [self._capture_value(c, stmts, freeze_name=True) for c in val])
                    if isinstance(val, list)
                    else self._capture_value(val, stmts, freeze_name=True)
                    for val in visited_value])
            if any(isinstance(val, list) for val in visited_value):
                # Several values with vectors among them, as a device
                # function returns: each is already a result of its own.
                for name, val in zip(names, visited_value):
                    if isinstance(val, list):
                        stmts.extend(self._assign_vector_from_ir(name, val))
                    else:
                        self._vector_vars.pop(name, None)
                        stmts.append(ir.IRAssign(target=name, value=val))
                    stmts.extend(self._store_unpacked(name, stores))
                return stmts
            visited_value = self._settle_components(visited_value, stmts, names)
            for name, val in zip(names, visited_value):
                self._vector_vars.pop(name, None)
                stmts.append(ir.IRAssign(target=name, value=val))
                stmts.extend(self._store_unpacked(name, stores))
            return stmts

        raise NotImplementedError("Cannot unpack non-tuple value")

    def _store_unpacked(self, temp: str, stores: dict) -> list:
        """Store an unpacked temporary to the subscript or component it is for.

        Called at the target's position among the targets, so its indices
        see the names assigned before it and not the ones after.
        """
        target = stores.get(temp)
        if target is None:
            return []
        value = ast.copy_location(ast.Name(id=temp, ctx=ast.Load()), target)
        assign = ast.copy_location(ast.Assign(targets=[target], value=value), target)
        # Statements the target's own indices need stay after the right
        # side and the earlier targets.
        saved = self._pre_stmts
        self._pre_stmts = []
        lowered = self.visit_Assign(assign)
        stmts = self._pre_stmts
        self._pre_stmts = saved
        stmts.extend(lowered if isinstance(lowered, list) else [lowered])
        return stmts

    # --- Expressions ---

    def visit_BinOp(self, node: ast.BinOp) -> ir.IRNode:
        if isinstance(node.op, ast.MatMult):
            left, right = self._visit_ordered([node.left, node.right])
            return self._matmul(node, left, right)
        op = self._binop_str(node.op)
        left, right = self._visit_ordered([node.left, node.right])

        # Vector-scalar or vector-vector binary ops, component by component
        if isinstance(left, list) or isinstance(right, list):
            return self._elementwise(
                node, f"'{op}'", [left, right],
                lambda pair: ir.IRBinOp(op=op, left=pair[0], right=pair[1]))

        return ir.IRBinOp(op=op, left=left, right=right)

    def visit_UnaryOp(self, node: ast.UnaryOp) -> ir.IRNode:
        op = self._unaryop_str(node.op)
        operand = self.visit(node.operand)

        # A signed integer literal is classified by its complete value.
        # In particular, -2**63 fits i64 even though its positive token does not.
        if op in ('+', '-') and isinstance(operand, ir.IRConstant) and isinstance(operand.value, int):
            return ir.IRConstant(-operand.value if op == '-' else operand.value)

        if isinstance(operand, list):
            return _like(operand, [ir.IRUnaryOp(op=op, operand=c) for c in operand])

        return ir.IRUnaryOp(op=op, operand=operand)

    def visit_Compare(self, node: ast.Compare) -> ir.IRNode:
        if len(node.ops) == 1:
            left, right = self._visit_ordered([node.left, node.comparators[0]])
            if isinstance(left, list) or isinstance(right, list):
                return self._vector_compare(node, [self._cmpop_str(node.ops[0])], [left, right])
            return ir.IRCompare(self._cmpop_str(node.ops[0]), left, right)

        operands = [self._visit_expression(n) for n in [node.left, *node.comparators]]
        if any(isinstance(value, list) for value, _ in operands):
            # Every link is evaluated, component by component; nothing
            # short-circuits, since each component has its own answer.
            values = []
            for value, before in operands:
                self._pre_stmts.extend(before)
                values.append(self._capture_value(value, self._pre_stmts))
            return self._vector_compare(node, [self._cmpop_str(op) for op in node.ops], values)
        if any(stmts for _, stmts in operands):
            name = self._fresh_name(f"__comparison_{self._inline_counter}__")
            self._inline_counter += 1
            left, before = operands[0]
            self._pre_stmts.extend(before)
            left = self._capture_value(left, self._pre_stmts)

            def lower_link(index, previous):
                right, before = operands[index + 1]
                body = list(before)
                right = self._capture_value(right, body)
                comparison = ir.IRCompare(self._cmpop_str(node.ops[index]), previous, right)
                body.append(ir.IRAssign(name, comparison))
                if index + 1 < len(node.ops):
                    body.append(ir.IRIf(ir.IRName(name), lower_link(index + 1, right), []))
                return body

            self._pre_stmts.extend(lower_link(0, left))
            return ir.IRName(name)

        # Desugar chained comparisons: a < b < c  →  (a < b) and (b < c)
        comparisons = []
        left = operands[0][0]
        for op_node, (right, _) in zip(node.ops, operands[1:]):
            op = self._cmpop_str(op_node)
            comparisons.append(ir.IRCompare(op=op, left=left, right=right))
            left = right

        if len(comparisons) == 1:
            return comparisons[0]
        return ir.IRBoolOp(op="and", values=comparisons)

    def _vector_compare(self, node, ops: list, values: list) -> VectorValue:
        """``v < w``, ``lo <= v < hi``: a vector of 0/1, one comparison per component.

        A scalar operand is compared with every component. Each link of a
        chain is a comparison vector of its own and the links are combined
        with ``and`` per component.
        """
        links = [self._elementwise(node, "comparison", [left, right],
                                   lambda row, op=op: ir.IRCompare(op, row[0], row[1]))
                 for op, left, right in zip(ops, values[:-1], values[1:], strict=True)]
        if len(links) == 1:
            return links[0]
        return self._elementwise(node, "comparison", links,
                                 lambda row: ir.IRBoolOp(op="and", values=list(row)))

    def visit_BoolOp(self, node: ast.BoolOp) -> ir.IRBoolOp:
        op = "and" if isinstance(node.op, ast.And) else "or"
        operands = [self._visit_expression(n) for n in node.values]
        values = [value for value, _ in operands]
        if any(isinstance(value, list) for value in values):
            # Over comparison vectors `and`/`or` act per component, and every
            # operand is evaluated: a component cannot short-circuit for the
            # others.
            captured = []
            for value, before in operands:
                self._pre_stmts.extend(before)
                captured.append(self._capture_value(value, self._pre_stmts))
            return self._elementwise(node, "boolean operator", captured,
                                     lambda row: ir.IRBoolOp(op=op, values=list(row)))
        if any(stmts for _, stmts in operands):
            name = self._fresh_name(f"__boolean_{self._inline_counter}__")
            self._inline_counter += 1
            value, before = operands[0]
            self._pre_stmts.extend(before)
            self._pre_stmts.append(ir.IRAssign(name, ir.IRCompare('!=', value, ir.IRConstant(0))))
            for value, before in operands[1:]:
                guard = ir.IRName(name)
                if op == 'or':
                    guard = ir.IRUnaryOp('not', guard)
                self._pre_stmts.append(ir.IRIf(
                    guard,
                    [*before, ir.IRAssign(name, ir.IRCompare('!=', value, ir.IRConstant(0)))],
                    [],
                ))
            return ir.IRName(name)
        return ir.IRBoolOp(op=op, values=values)

    def visit_Subscript(self, node: ast.Subscript) -> ir.IRNode:
        # Vector component access: v[0], or v[k] for a runtime k
        if isinstance(node.value, ast.Name) and node.value.id in self._vector_vars:
            return self._vector_component(node, self._variable_value(node.value.id))
        # A component of a vector or matrix constant: SUN[2], ROT[1, 0]
        if isinstance(node.value, (ast.Name, ast.Attribute)):
            named = self._named_constant(node.value)      # None for a local or a field
            if isinstance(named, VectorValue):
                return self._vector_component(node, named)

        # A component of a vector-valued expression: vf[i][c], f(x)[c], (a @ b)[0, 1]
        if isinstance(node.value, (ast.Subscript, ast.Call, ast.BinOp)):
            inner, statements = self._visit_expression(node.value)
            self._pre_stmts.extend(statements)
            if isinstance(inner, list):
                return self._vector_component(node, inner)
            raise self._source_error(
                node, "subscript", "indexes a scalar value; only fields, local and "
                "shared arrays, and vectors can be indexed")

        # field.shape[k] — a dimension query, not a load from a field
        dim_size = self._as_dim_size(node)
        if dim_size is not None:
            return dim_size

        # Get field name for vector field detection
        field_name = node.value.id if isinstance(node.value, ast.Name) else None
        is_vector_field = field_name is not None and field_name in self._vector_fields

        # Compute the linearized index (handles multi-dim, None, etc.)
        index = self._visit_subscript_index(node)
        field_ir = self.visit(node.value)

        # Vector field load: expand to n component loads
        if is_vector_field:
            ndim = self._vector_fields[field_name]
            # Cast index to int before computing component offsets so that
            # a float index like 127.7 maps to element 127, not a fractional
            # position that shifts the component access.
            int_index = self._element_index(index)
            return VectorValue(
                (ir.IRFieldLoad(field=field_ir, index=self._component_index(int_index, ndim, c))
                 for c in range(ndim)), self._matrix_fields.get(field_name))

        return ir.IRFieldLoad(field=field_ir, index=index)

    def _as_dim_size(self, node: ast.Subscript) -> ir.IRDimSize | None:
        """`f.shape[k]` on a field → IRDimSize, which resolve_ir folds.

        Emitting a generic IRAttribute here is what limited `.shape` to the
        outermost loop bound: dispatch evaluated that one expression
        numerically, and every other position reached codegen unresolved.
        IRDimSize is the node the resolve pass already knows how to fold,
        and it recurses through every body.
        """
        value = node.value
        if not (isinstance(value, ast.Attribute) and value.attr == "shape"):
            return None
        if not isinstance(value.value, ast.Name):
            return None
        index = node.slice
        if not (isinstance(index, ast.Constant) and isinstance(index.value, int)):
            raise NotImplementedError(
                f"'{value.value.id}.shape[...]' needs a constant dimension "
                f"index; the shape is resolved when the kernel is compiled."
            )
        return ir.IRDimSize(field_name=value.value.id, dim=index.value)

    def visit_Attribute(self, node: ast.Attribute) -> ir.IRAttribute:
        # module.NAME bound to a tack.constant reads as its value
        named = self._named_constant(node)
        if named is not None:
            return named
        # math.pi, math.e and math.tau are literals too
        value = self._call_bindings.math_constant(node)
        if value is not None:
            return ir.IRConstant(value)
        obj = self.visit(node.value)
        if isinstance(obj, list):
            # v.x on a vector variable or a vector-valued expression
            if len(getattr(obj, 'shape', ())) == 2:
                raise self._source_error(
                    node, "attribute", f"'{node.attr}' names a component of a vector; "
                    f"a matrix entry is m[i, j]")
            return obj[self._named_component(node, len(obj))]
        return ir.IRAttribute(obj=obj, attr=node.attr)

    def _named_component(self, node: ast.Attribute, n: int) -> int:
        """The index that ``x``, ``y``, ``z`` or ``w`` names in an n-vector."""
        c = COMPONENT_NAMES.find(node.attr) if len(node.attr) == 1 else -1
        if not 0 <= c < n:
            names = ", ".join(COMPONENT_NAMES[:n])
            raise self._source_error(
                node, "attribute", f"'{node.attr}' is not a component of a {n}-vector; "
                f"use {names} or an index")
        return c

    def _component_target(self, target):
        """An assignment target ``v.x`` or ``vf[i].x`` as the subscript it names."""
        if not isinstance(target, ast.Attribute):
            return target
        vector = target.value
        if isinstance(vector, ast.Name) and vector.id in self._vector_vars:
            n = self._vector_vars[vector.id]
            is_matrix = vector.id in self._matrix_vars
        elif (isinstance(vector, ast.Subscript) and isinstance(vector.value, ast.Name)
                and vector.value.id in self._vector_fields):
            n = self._vector_fields[vector.value.id]
            is_matrix = vector.value.id in self._matrix_fields
        else:
            return target
        if is_matrix:
            raise self._source_error(
                target, "attribute", f"'{target.attr}' names a component of a vector; "
                f"a matrix entry is m[i, j]")
        index = ast.copy_location(ast.Constant(self._named_component(target, n)), target)
        return ast.copy_location(ast.Subscript(value=vector, slice=index, ctx=target.ctx), target)

    def _named_constant(self, node):
        """The value of a name bound to a tack.constant: a scalar's IR, or a
        vector or matrix constant's components as a VectorValue."""
        bound = self._call_bindings.resolve(node)
        scalar = constant_ir(bound)
        if scalar is not None:
            return scalar
        components = constant_components(bound)
        if components is None:
            return None
        values, shape = components
        if len(shape) == 2 and max(shape) > MAX_MATRIX_EXTENT:
            raise self._source_error(
                node, "constant", f"is a {shape[0]}x{shape[1]} matrix, larger than "
                f"{MAX_MATRIX_EXTENT}x{MAX_MATRIX_EXTENT}")
        value = VectorValue(values, shape)
        # Read at a runtime index, the constant is one table load
        # (_vector_component); derived vectors carry no table.
        value.table = constant_table(bound)
        return value

    def visit_Name(self, node: ast.Name) -> ir.IRNode:
        # A name the function does not bind, bound to a tack.constant in the
        # scope that defines it, reads as that value. Locals and parameters
        # resolve as themselves, so they shadow a constant of the same name.
        if isinstance(node.ctx, ast.Load):
            named = self._named_constant(node)
            if named is not None:
                return named
        source = None
        if hasattr(node, 'lineno'):
            source = (node.lineno, node.col_offset + 1,
                      self._inline_stack[-1] if self._inline_stack else None)
            self._name_reads.setdefault(node.id, source)
        # If this name is a vector variable, return its components as a list
        if node.id in self._vector_vars:
            return self._variable_value(node.id)
        name = ir.IRName(name=node.id)
        # This read's position and source spelling, for scope errors.
        name._source = source
        name._source_id = getattr(node, '_source_id', node.id)
        return name

    def visit_Constant(self, node: ast.Constant) -> ir.IRConstant:
        return ir.IRConstant(value=node.value)

    def visit_Tuple(self, node: ast.Tuple) -> list:
        """Visit tuple — used for multi-dimensional indexing like field[i, j]."""
        return TupleValue(self._visit_ordered(node.elts))

    def visit_List(self, node: ast.List) -> VectorValue:
        """A list of scalars is a vector: ``[x, y]`` is ``tack.Vector([x, y])``."""
        return VectorValue(self._visit_ordered(node.elts))

    def _variable_value(self, name: str) -> VectorValue:
        """The components of the vector or matrix variable ``name``."""
        return VectorValue((ir.IRName(self._component_name(name, c))
                            for c in range(self._vector_vars[name])),
                           self._matrix_vars.get(name))

    def _bind_vector(self, name: str, value: list):
        """Record that the variable ``name`` holds the vector or matrix ``value``."""
        self._vector_vars[name] = len(value)
        shape = getattr(value, 'shape', None)
        if shape is not None and len(shape) == 2:
            self._matrix_vars[name] = shape
        else:
            self._matrix_vars.pop(name, None)

    def _field_shape(self, name: str) -> tuple:
        """The shape of one element of the vector or matrix field ``name``."""
        return self._matrix_fields.get(name) or (self._vector_fields[name],)

    def visit_Call(self, node: ast.Call) -> ir.IRNode:
        # Check for @tack.func calls → inline
        func_obj = self._call_bindings.device_func(node.func)
        if func_obj is not None:
            return self._inline_func_call(func_obj, node)
        func_name = self._resolve_call_name(node)

        # Vector constructor: Vector([a, b, c]) or tack.Vector([a, b, c])
        if func_name == "Vector":
            return self._visit_vector_construct(node)

        # Matrix constructors: Matrix([[a, b], [c, d]]), Matrix.identity(n)
        if func_name == "Matrix":
            return self._visit_matrix_construct(node)
        if func_name == "identity" and self._names_matrix(node.func):
            return self._visit_matrix_identity(node)

        # v.min(), v.max(), v.sum(): a vector's own reduction, which shares
        # its name with a builtin of two or more arguments
        if (isinstance(node.func, ast.Attribute) and not node.args
                and func_name in ('min', 'max', 'sum')):
            reduced = self._try_visit_vector_method(node)
            if reduced is not None:
                return reduced
            raise NotImplementedError(
                f"{func_name}() without arguments reduces a vector's components; "
                f"a field is reduced from Python, with field.{func_name}()")

        # Math builtins from the math module or bare names
        if func_name in MATH_BUILTINS:
            if func_name in ('min', 'max'):
                # Python's min and max take any number of values
                if len(node.args) < 2:
                    raise NotImplementedError(f"{func_name}() takes at least 2 arguments")
                args = self._visit_ordered(node.args)
                result = args[0]
                for arg in args[1:]:
                    result = self._math_call(node, func_name, [result, arg])
                return result
            arity = 2 if func_name in ('atan2', 'pow') else 1
            if len(node.args) != arity:
                raise NotImplementedError(f"{func_name}() takes exactly {arity} arguments")
            return self._math_call(node, func_name, self._visit_ordered(node.args))

        # any(v), all(v): a comparison vector reduced to one truth value
        if func_name in ("any", "all"):
            if len(node.args) != 1:
                raise NotImplementedError(f"{func_name}() takes exactly one argument")
            mask = self.visit(node.args[0])
            if not isinstance(mask, VectorValue):
                raise self._source_error(
                    node, f"{func_name}()", "reduces a vector or matrix of comparisons; "
                    "a scalar is already a truth value")
            return ir.IRBoolOp(op="or" if func_name == "any" else "and", values=list(mask))

        # tack.select(mask, a, b): per component, a where mask is true, else b
        if func_name == "select":
            if len(node.args) != 3:
                raise NotImplementedError("select() takes exactly 3 arguments (mask, a, b)")
            mask, a, b = self._visit_ordered(node.args)
            if not any(isinstance(v, list) for v in (mask, a, b)):
                return ir.IRIfExp(mask, a, b)
            return self._elementwise(node, "select()", [mask, a, b],
                                     lambda row: ir.IRIfExp(row[0], row[1], row[2]))

        # len(field) → the field's first dimension
        if func_name == "len":
            if len(node.args) != 1:
                raise NotImplementedError("len() takes exactly one argument")
            target = node.args[0]
            if isinstance(target, ast.Name) and target.id not in self._vector_vars:
                return ir.IRDimSize(field_name=target.id, dim=0)
            arg = self.visit(target)
            return ir.IRAttribute(obj=arg, attr="__len__")

        # range() is handled in visit_For; if it appears elsewhere, error
        if func_name == "range":
            raise NotImplementedError("range() outside of for-loop not supported")

        # ndrange() outside of for-loop
        if func_name == "ndrange":
            raise NotImplementedError("ndrange() outside of for-loop not supported")

        # Shared memory: tack.shared(dtype, size) or tack.shared_like(field, size)
        if func_name == "shared":
            raise NotImplementedError(
                "tack.shared() must be used in an assignment: smem = tack.shared(tack.f32, 256)")
        if func_name == "shared_like":
            raise NotImplementedError(
                "tack.shared_like() must be used in an assignment: smem = tack.shared_like(field, 256)")

        # Local array: tack.local_array(dtype, size) or tack.local_array_like(field, size)
        if func_name == "local_array":
            raise NotImplementedError(
                "tack.local_array() must be used in an assignment: arr = tack.local_array(tack.f32, 8)")
        if func_name == "local_array_like":
            raise NotImplementedError(
                "tack.local_array_like() must be used in an assignment: arr = tack.local_array_like(field, 8)")

        # Block reductions: tack.block_sum(val), tack.block_max(val), tack.block_min(val)
        if func_name in ("block_sum", "block_max", "block_min"):
            if len(node.args) != 1:
                raise NotImplementedError(f"tack.{func_name}() takes exactly 1 argument")
            op = func_name.replace("block_", "")  # "sum", "max", "min"
            return ir.IRBlockReduce(op=op, value=self.visit(node.args[0]))

        # Barrier: tack.barrier()
        if func_name == "barrier":
            return ir.IRBarrier()

        # Thread ID: tack.thread_id()
        if func_name == "thread_id":
            return ir.IRThreadId()

        # Atomic operations: atomic_add, atomic_min, atomic_max
        if func_name in ("atomic_add", "atomic_min", "atomic_max"):
            if len(node.args) != 3:
                raise NotImplementedError(f"{func_name}() takes exactly 3 arguments (field, index, value)")
            return self._visit_atomic(node, func_name, as_statement=False)

        # print() for kernel debugging
        if func_name == "print":
            format_parts = []
            expr_nodes = []
            for arg in node.args:
                if isinstance(arg, ast.Constant) and isinstance(arg.value, str):
                    format_parts.append(("str", arg.value))
                else:
                    format_parts.append(("expr", len(expr_nodes)))
                    expr_nodes.append(arg)
            return ir.IRPrint(args=self._visit_ordered(expr_nodes), format_parts=format_parts)

        # Type casts: int(), float(), and explicit tack.f32/f64/i32/i64/u32/u64
        _CAST_MAP = {
            "int": i32, "float": f32,
            "i8": i8, "u8": u8,
            "i16": i16, "u16": u16,
            "i32": i32, "u32": u32,
            "i64": i64, "u64": u64,
            "f32": f32, "f64": f64,
        }
        if func_name in _CAST_MAP:
            if len(node.args) != 1:
                raise NotImplementedError(f"{func_name}() takes exactly one argument")
            value = self.visit(node.args[0])
            if isinstance(value, list):
                return _like(value, [ir.IRCast(value=c, dtype=_CAST_MAP[func_name]) for c in value])
            return ir.IRCast(value=value, dtype=_CAST_MAP[func_name])

        # Check for texture3d.sample(u, v, w)
        if isinstance(node.func, ast.Attribute) and node.func.attr == "sample":
            tex_name = getattr(node.func.value, 'id', None)
            if tex_name and tex_name in self._texture_fields:
                if len(node.args) != 3:
                    raise TypeError("sample() takes exactly 3 arguments (u, v, w)")
                coords = [self.visit(a) for a in node.args]
                # Use the original kernel param name, not the inlined rename
                original_name = self._texture_origin.get(tex_name, tex_name)
                return ir.IRTextureSample(
                    field_name=original_name, coords=coords)

        # Check for vector method calls: v.normalized(), v.cross(w), v.dot(w), v.norm()
        if isinstance(node.func, ast.Attribute):
            obj_result = self._try_visit_vector_method(node)
            if obj_result is not None:
                return obj_result

        raise NotImplementedError(f"Function call '{func_name}' not supported in kernels")

    def _math_call(self, node, func_name: str, args: list):
        """A math builtin on scalars, or on each component when given a vector."""
        if any(isinstance(a, list) for a in args):
            return self._elementwise(node, f"{func_name}()", args,
                                     lambda row: ir.IRCall(func_name=func_name, args=row))
        return ir.IRCall(func_name=func_name, args=args)

    def _visit_atomic(self, node: ast.Call, func_name: str, *, as_statement: bool):
        """``tack.atomic_<op>(field, index, value)``.

        The index is a flat index, or a tuple with one index per dimension,
        where a vector supplies one per component. On a vector field a
        vector value updates each component of the element the index
        names, one atomic per component. A scalar value there keeps the
        older meaning: the index is the flat index of one component.

        As a statement the atomic is its own IR node. Anywhere else its
        value is the element's value before the update, assigned to a
        temporary among the pre-statements so that it takes effect in
        source order relative to the other operands (C leaves the order of
        operands unspecified); the expression then reads the temporary.
        """
        op = func_name.replace("atomic_", "")  # "add", "min", "max"
        field_node = node.args[0]
        field_name = field_node.id if isinstance(field_node, ast.Name) else None
        field, index, value = self._visit_ordered(node.args)
        by_dimension = isinstance(index, list)
        if by_dimension:
            if field_name is None:
                raise self._source_error(
                    node, f"{func_name}()", "needs a named field for an index per dimension")
            index = self._linearize_index(node, field_name, index)
        ndim = self._vector_fields.get(field_name)
        if not isinstance(value, list):
            if by_dimension and ndim is not None:
                raise self._source_error(
                    node, f"{func_name}()", f"names an element of a field of {ndim}-vectors; "
                    f"give it a {ndim}-vector, or the flat index of one component")
            atomic = ir.IRAtomicOp(op=op, field=field, index=index, value=value)
            if as_statement:
                return atomic
            return self._capture_atomic(atomic)
        if ndim is None:
            raise self._source_error(
                node, f"{func_name}()", "gives a vector to a field of scalars")
        if len(value) != ndim:
            raise self._source_error(
                node, f"{func_name}()", f"gives a {len(value)}-vector to a field of {ndim}-vectors")
        # One atomic per component, each a statement among the
        # pre-statements; as an expression the value is the vector of the
        # components' old values.
        element = self._element_index(self._capture_value(index, self._pre_stmts))
        value = self._settle_components(value, self._pre_stmts)
        olds = []
        for c, component in enumerate(value):
            atomic = ir.IRAtomicOp(
                op=op, field=field, index=self._component_index(element, ndim, c),
                value=component)
            if as_statement:
                self._pre_stmts.append(atomic)
            else:
                olds.append(self._capture_atomic(atomic))
        return VectorValue(olds, (ndim,)) if not as_statement else []

    def _capture_atomic(self, atomic: ir.IRAtomicOp) -> ir.IRName:
        """Perform the atomic now, in a pre-statement, and read its old value."""
        name = self._fresh_name(f"__atomic_{self._inline_counter}__")
        self._inline_counter += 1
        self._pre_stmts.append(ir.IRAssign(name, atomic))
        return ir.IRName(name)

    def visit_Expr(self, node: ast.Expr) -> ir.IRNode:
        """Expression statement (e.g., standalone function call)."""
        # Skip docstrings and other standalone string constants
        if isinstance(node.value, ast.Constant) and isinstance(node.value.value, str):
            return None
        atomic = self._atomic_call_name(node.value)
        if atomic is not None:
            # A statement of its own: the old value is not wanted.
            value = self._visit_atomic(node.value, atomic, as_statement=True)
            return None if isinstance(value, list) else value
        value = self.visit(node.value)
        # A function/atomic expression can have generated all its effects
        # in pre-statements. Its scalar result is unused here.
        return None if isinstance(value, (ir.IRName, list)) else value

    def _atomic_call_name(self, node):
        """``'atomic_add'`` etc. when ``node`` is a call of a Tack atomic, else None."""
        if not isinstance(node, ast.Call) or self._call_bindings.device_func(node.func):
            return None
        try:
            name = self._call_bindings.call_name(node.func)
        except NotImplementedError:
            return None
        return name if name in ('atomic_add', 'atomic_min', 'atomic_max') else None

    # --- @tack.func inlining ---

    def _inline_func_call(self, func_obj, call_node: ast.Call):
        """Inline a @tack.func call, tracking it for diagnostics."""
        # Arguments belong to the caller's source; visiting them first
        # records their positions before the callee's are in play.
        for arg in call_node.args:
            for sub in ast.walk(arg):
                if (isinstance(sub, ast.Name) and hasattr(sub, 'lineno')
                        and sub.id not in self._name_reads):
                    self._name_reads[sub.id] = (
                        sub.lineno, sub.col_offset + 1,
                        self._inline_stack[-1] if self._inline_stack else None)
        # Template methods are renamed; diagnostics use the source name.
        self._inline_stack.append(func_obj.func.__name__)
        try:
            return self._inline_func_body(func_obj, call_node)
        finally:
            self._inline_stack.pop()

    def _inline_func_body(self, func_obj, call_node: ast.Call):
        """Inline a @tack.func call at the call site.

        Produces a list of IR statements (parameter assignments + body),
        and returns the result variable name as an IRName.
        """
        from tack.lang.call_bindings import CallBindings
        func_name = func_obj.name
        funcdef = func_obj._funcdef
        callee_bindings = CallBindings(funcdef, func_obj.func,
                                      template_funcs=self._template_funcs)
        validate_source(funcdef, kind='Device function', call_bindings=callee_bindings)

        # Save and reset _pre_stmts so nested inlining doesn't interfere
        saved_pre_stmts = self._pre_stmts
        self._pre_stmts = []

        # Unique suffix to avoid name collisions across multiple inlines
        suffix = self._inline_counter
        self._inline_counter += 1

        # Map callee params to caller args
        callee_params = [a.arg for a in funcdef.args.args]
        if len(call_node.args) != len(callee_params):
            raise TypeError(
                f"@tack.func '{func_name}' expects {len(callee_params)} args, "
                f"got {len(call_node.args)}"
            )

        # Create a name renamer for the callee's body
        rename_map = {}
        for param_name in callee_params:
            rename_map[param_name] = self._fresh_name(f"__{func_name}_{param_name}_{suffix}__")

        # Detect return count: 0=void, 1=scalar, >1=tuple
        n_returns = self._detect_return_count(funcdef)
        if n_returns == 0:
            result_var = None
        elif n_returns > 1:
            result_var = [self._fresh_name(f"__{func_name}_ret_{c}_{suffix}__")
                          for c in range(n_returns)]
        else:
            result_var = self._fresh_name(f"__{func_name}_ret_{suffix}__")

        # Rename all local variables in the callee body to avoid collisions
        # We collect all assigned names and create renames for them
        assigned_names = self._collect_assigned_names(funcdef.body)
        for name in sorted(assigned_names):
            if name not in rename_map:
                rename_map[name] = self._fresh_name(f"__{func_name}_{name}_{suffix}__")

        # Override rename map for local array / shared memory params:
        # alias the caller's array name directly so the inlined body
        # accesses it without an assignment (arrays can't be assigned in C).
        # Must happen BEFORE the renamer runs.
        for param_name in callee_params:
            if isinstance(call_node.args[callee_params.index(param_name)], ast.Name):
                arg_name = call_node.args[callee_params.index(param_name)].id
                if arg_name in self._shared_vars:
                    rename_map[param_name] = arg_name

        # Rename the callee AST (deep copy first)
        renamed_body = _structure_returns(copy.deepcopy(funcdef.body), func_name)
        renamer = _NameRenamer(rename_map, result_var)
        # Flatten in case visit_Return returns a list (multi-return)
        flat_body = []
        for stmt in renamed_body:
            result = renamer.visit(stmt)
            if isinstance(result, list):
                flat_body.extend(result)
            else:
                flat_body.append(result)
        renamed_body = flat_body

        # Propagate vector-ness and texture metadata for renamed parameters
        # (must happen before parameter assignments so we can skip texture assigns)
        for param_name in callee_params:
            renamed = rename_map[param_name]
            if isinstance(call_node.args[callee_params.index(param_name)], ast.Name):
                arg_name = call_node.args[callee_params.index(param_name)].id
                if arg_name in self._vector_vars:
                    self._bind_vector(renamed, self._variable_value(arg_name))
                if arg_name in self._vector_fields:
                    # A vector field passed in: `fld[i]` in the body must
                    # expand to its components, as it does in the caller.
                    self._vector_fields[renamed] = self._vector_fields[arg_name]
                    if arg_name in self._matrix_fields:
                        self._matrix_fields[renamed] = self._matrix_fields[arg_name]
                if arg_name in self._texture_fields:
                    self._texture_fields[renamed] = self._texture_fields[arg_name]
                    self._texture_origin[renamed] = self._texture_origin.get(arg_name, arg_name)

        # Emit parameter assignments
        stmts = []
        for param_name, arg_ast in zip(callee_params, call_node.args):
            renamed = rename_map[param_name]
            # Skip assignment for texture params and local array params —
            # these are aliased to the caller's variable directly.
            if renamed in self._texture_fields:
                continue
            if renamed in self._shared_vars:
                continue
            arg_val = self.visit(arg_ast)
            # Capture any stmts from visiting this arg (e.g. nested inlines)
            stmts.extend(self._pre_stmts)
            self._pre_stmts = []
            if isinstance(arg_val, list):
                # Vector argument — assign each component
                ndim = len(arg_val)
                self._bind_vector(renamed, arg_val)
                for c in range(ndim):
                    stmts.append(ir.IRAssign(
                        target=self._component_name(renamed, c), value=arg_val[c]))
            else:
                stmts.append(ir.IRAssign(target=renamed, value=arg_val))

        # Visit the renamed body statements
        if func_obj in self._active_funcs:
            raise NotImplementedError(f"Recursive @tack.func '{func_name}' is not supported")
        caller_bindings = self._call_bindings
        callee_bindings.locals.update(rename_map.values())
        self._call_bindings = callee_bindings
        self._active_funcs.add(func_obj)
        try:
            body_ir = self._visit_body(renamed_body)
        finally:
            self._active_funcs.remove(func_obj)
            self._call_bindings = caller_bindings
        stmts.extend(body_ir)

        # Restore saved pre_stmts and append all inline stmts
        self._pre_stmts = saved_pre_stmts
        self._pre_stmts.extend(stmts)

        # Void function: no return value
        if result_var is None:
            return None

        # Multi-return: one value per element, a vector element as its
        # components (a nested list)
        if isinstance(result_var, list):
            return TupleValue(self._result_value(v) for v in result_var)

        return self._result_value(result_var)

    def _result_value(self, result_var: str):
        """An inlined call's result: a name, or a vector's component names."""
        if result_var in self._vector_vars:
            return self._variable_value(result_var)
        return ir.IRName(result_var)

    def _collect_assigned_names(self, stmts) -> set[str]:
        """Collect all variable names assigned in a list of AST statements.

        Every binding counts, including the names inside a tuple target
        (`t, u = f()`, `for i, j in ndrange(...)`): a callee local that is
        not collected is not renamed, and the inlined body then writes
        the caller's variable of the same name.
        """
        names = set()

        def targets(node):
            if isinstance(node, ast.Name):
                names.add(node.id)
            elif isinstance(node, (ast.Tuple, ast.List)):
                for elt in node.elts:
                    targets(elt)

        for stmt in stmts:
            for node in ast.walk(stmt):
                if isinstance(node, ast.Assign):
                    for t in node.targets:
                        targets(t)
                elif isinstance(node, ast.AugAssign):
                    targets(node.target)
                elif isinstance(node, ast.For):
                    targets(node.target)
        return names

    def _detect_return_count(self, funcdef) -> int:
        """Detect if a function returns a tuple (multi-return).

        Returns the number of return values (0 for void, 1 for scalar, >1 for tuple).
        """
        for node in ast.walk(funcdef):
            if isinstance(node, ast.Return) and node.value:
                if isinstance(node.value, ast.Tuple):
                    return len(node.value.elts)
                return 1
        return 0

