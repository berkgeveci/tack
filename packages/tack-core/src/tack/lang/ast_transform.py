    def _resolve_call_name(self, node: ast.Call) -> str:
        """Resolve the function name from a Call node.

        Handles:
          - bare name: sqrt(x) → "sqrt"
          - module attribute: math.sqrt(x) → "sqrt"
          - tack attribute: tack.sqrt(x) → "sqrt"
        """
